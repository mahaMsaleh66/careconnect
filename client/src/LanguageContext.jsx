const LanguageContext = createContext();

function applyDocumentLang(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ur' ? 'rtl' : 'ltr';
}

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem('cc_lang');
    const next = saved === 'ur' ? 'ur' : 'en';
    if (typeof document !== 'undefined') applyDocumentLang(next);
    return next;
  });

  useEffect(() => {
    applyDocumentLang(lang);
    localStorage.setItem('cc_lang', lang);
  }, [lang]);

  const value = useMemo(() => {
    const t = (key, fallback) => {
      const table = dictionaries[lang] || dictionaries.en;
      let text = table[key] || dictionaries.en[key] || fallback || key;
      return text;
    };
    const tName = (key, vars) => {
      let text = t(key);
      if (vars) {
        Object.keys(vars).forEach((k) => {
          text = text.replace('{' + k + '}', vars[k]);
        });
      }
      return text;
    };
    const setLang = (next) => setLangState(next === 'ur' ? 'ur' : 'en');
    const toggleLang = () => setLangState((cur) => (cur === 'ur' ? 'en' : 'ur'));
    return { lang, setLang, toggleLang, t, tName };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
